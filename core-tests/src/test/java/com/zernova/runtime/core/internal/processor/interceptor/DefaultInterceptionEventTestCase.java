package com.zernova.runtime.core.internal.processor.interceptor;

import static com.zernova.runtime.api.message.Message.of;
import static com.zernova.runtime.core.api.event.EventContextFactory.create;

import static java.util.Optional.empty;

import static org.hamcrest.MatcherAssert.assertThat;
import static org.hamcrest.Matchers.is;

import com.zernova.runtime.api.exception.ZernovaException;
import com.zernova.runtime.core.internal.event.InternalEvent;
import com.zernova.runtime.core.internal.interception.DefaultInterceptionEvent;
import com.zernova.tck.junit4.AbstractZernovaTestCase;

import org.junit.Test;

public class DefaultInterceptionEventTestCase extends AbstractZernovaTestCase {

  @Test
  public void correlationIdAutogenerated() throws ZernovaException {
    final InternalEvent event =
        InternalEvent.builder(create("id", "serverId", TEST_CONNECTOR_LOCATION, null, empty()))
            .message(of(TEST_PAYLOAD)).build();

    final DefaultInterceptionEvent interceptionEvent = new DefaultInterceptionEvent(event);

    assertThat(interceptionEvent.getCorrelationId(), is("id"));
  }

  @Test
  public void correlationIdGiven() throws ZernovaException {
    final InternalEvent event =
        InternalEvent.builder(create("id", "serverId", TEST_CONNECTOR_LOCATION, "corr1", empty()))
            .message(of(TEST_PAYLOAD)).build();

    final DefaultInterceptionEvent interceptionEvent = new DefaultInterceptionEvent(event);

    assertThat(interceptionEvent.getCorrelationId(), is("corr1"));
  }

  @Test
  public void correlationIdLegacy() throws ZernovaException {
    final InternalEvent event =
        InternalEvent.builder(create("id", "serverId", TEST_CONNECTOR_LOCATION, null, empty()))
            .correlationId("corr1").message(of(TEST_PAYLOAD)).build();

    final DefaultInterceptionEvent interceptionEvent = new DefaultInterceptionEvent(event);

    assertThat(interceptionEvent.getCorrelationId(), is("corr1"));
  }

}
