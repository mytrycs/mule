#!/usr/bin/env python3
"""Compile original portable Transform support against the qualified engine APIs."""
from pathlib import Path
import subprocess, tempfile,zipfile,os,base64
root=Path(__file__).resolve().parents[2]
src=Path(__file__).resolve().parent
bundle=root/'zernova-studio-kernel/runtime'
out=src/'transform-support.jar'
cp=os.pathsep.join(str(p) for p in (bundle/'engine/lib').rglob('*.jar'))
with tempfile.TemporaryDirectory() as tmp:
 subprocess.run([os.environ.get('JAVAC','javac'),'--release','17','-cp',cp,'-d',tmp,*[str(p) for p in (src/'src').rglob('*.java')]],check=True)
 with zipfile.ZipFile(out,'w',zipfile.ZIP_DEFLATED) as z:
  def add(name,data):
   info=zipfile.ZipInfo(name,(1980,1,1,0,0,0));info.compress_type=zipfile.ZIP_DEFLATED;z.writestr(info,data)
  for p in sorted(Path(tmp).rglob('*.class')):add(p.relative_to(tmp).as_posix(),p.read_bytes())
  for p in sorted((src/'resources').rglob('*')):
   if p.is_file():add(p.relative_to(src/'resources').as_posix(),p.read_bytes())
  add('META-INF/services/com.zernova.runtime.extension.api.provider.RuntimeExtensionModelProvider','com.zernova.studio.transform.TransformModel\n')
  for api,name in [('component.ComponentBuildingDefinitionProvider','TransformDefinitions'),('xml.XmlNamespaceInfoProvider','TransformNamespace')]:add('META-INF/services/com.zernova.runtime.dsl.api.'+api,'com.zernova.studio.transform.'+name+'\n')
(root/'zernova-studio-build/src/portable/transformSupport.ts').write_text('// Generated by transform-support/build.py from accompanying original Java sources.\nexport const TRANSFORM_SUPPORT = '+repr(base64.b64encode(out.read_bytes()).decode())+';\n')
print(out)
